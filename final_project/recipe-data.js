  const recipeDetail = document.getElementById("recipeDetail");
  
  function getRecipeFavorites() {
    return JSON.parse(localStorage.getItem("tinyBitesRecipeFavorites")) || [];
  }
  
  function saveRecipeFavorites(favorites) {
    localStorage.setItem("tinyBitesRecipeFavorites", JSON.stringify(favorites));
  }
  
  function isRecipeFavorite(recipeId) {
    return getRecipeFavorites().includes(recipeId);
  }
  
  function toggleRecipeFavorite(recipeId) {
    let favorites = getRecipeFavorites();
  
    if (favorites.includes(recipeId)) {
      favorites = favorites.filter(function (id) {
        return id !== recipeId;
      });
    } else {
      favorites.push(recipeId);
    }
  
    saveRecipeFavorites(favorites);
    updateRecipeFavoriteButton(recipeId);
  }
  
  function updateRecipeFavoriteButton(recipeId) {
    const button = document.getElementById("recipeFavoriteButton");
  
    if (!button) return;
  
    if (isRecipeFavorite(recipeId)) {
      button.textContent = "♥ Saved";
      button.classList.add("saved");
    } else {
      button.textContent = "♡ Save to favorites";
      button.classList.remove("saved");
    }
  }
  
  if (recipeDetail) {
    const params = new URLSearchParams(window.location.search);
    const recipeId = params.get("id");
    const recipe = recipes[recipeId];
  
    if (recipe) {
      const ingredientList = recipe.ingredients
        .map(function (item) {
          return `<li>${item}</li>`;
        })
        .join("");
  
      const stepList = recipe.steps
        .map(function (step) {
          return `<li>${step}</li>`;
        })
        .join("");
  
      recipeDetail.innerHTML = `
        <section class="category-hero breakfast-theme">
          <p class="small-label">${recipe.category}</p>
          <h2>${recipe.emoji} ${recipe.title}</h2>
          <p>${recipe.intro}</p>
  
          <button id="recipeFavoriteButton" class="favorite-button" type="button">
            ♡ Save to favorites
          </button>
        </section>
  
        <section class="recipe-detail-card">
          <div>
            <p class="recipe-tag">${recipe.tag}</p>
            <h3>Ingredients</h3>
            <ul>${ingredientList}</ul>
          </div>
  
          <div>
            <h3>Steps</h3>
            <ol>${stepList}</ol>
          </div>
        </section>
      `;
  
      document
        .getElementById("recipeFavoriteButton")
        .addEventListener("click", function () {
          toggleRecipeFavorite(recipeId);
        });
  
      updateRecipeFavoriteButton(recipeId);
    } else {
      recipeDetail.innerHTML = `
        <section class="category-hero">
          <h2>Recipe not found.</h2>
          <a href="breakfast.html">Back to breakfast</a>
        </section>
      `;
    }
  }